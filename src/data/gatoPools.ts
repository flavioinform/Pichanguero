// Curated candidate pools for Gato futbolero grid generation, tiered by
// difficulty. Clubs are ranked by nationality diversity (distinct capped
// countries among current+historical players), not raw squad size — a club
// with 300 mostly-domestic players is a worse grid criterion than one with
// 100 players from 40 different countries. The easy tier is a hand-picked
// list of globally famous clubs (kept even where their diversity score
// alone wouldn't rank them this high) so easy mode reliably surfaces teams
// like Real Madrid or Chelsea; medium/hard are the next tiers by diversity.
// Countries are similarly tiered by number of capped players.
//
// Each difficulty draws cumulatively (medium = easy+medium pool, hard =
// all three) — see src/lib/gatoGrid.ts for how generateGatoGrid() uses
// CLUB_COMPATIBLE_COUNTRIES (precomputed offline, no live queries needed)
// to build a grid instantly. This is a snapshot of the dataset at
// generation time (2026-09-07); regenerate if the tables are re-imported
// with materially different data.

export type Difficulty = 'easy' | 'medium' | 'hard';

